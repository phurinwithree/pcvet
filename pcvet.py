import psutil #เรียกใช้ ไลเบอรี่ psutil

cpu = psutil.cpu_percent(interval=1) #กำหนดตัวแปร cpu เพื่อรับค่าการใช้งาน ณ เวลา 1 วินาที
disk = psutil.disk_usage("C:\\") #กำหนดตัวแปร disk เพื่อรับค่าการใช้งาน disk ทั้งหมดของ ไดรฟ์ C: และใช้ \\ เพราะต้องการให้ python ใช้เครื่องหมาย \

# _U ย่อมาจาก USE
print("Cpu_U:", cpu , "%") #แสดงผลค่า ตัวแปร cpu ต่อท้ายด้วยเครื่องหมาย % 
print("Disk_U:", disk.percent, "%") #แสดงผลค่า ตัวแปร disk แต่เอาแค่เปอเซ็นเท่านั้นต่อท้ายด้วยเครื่องหมาย %